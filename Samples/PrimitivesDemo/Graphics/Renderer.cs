using DigitalRiseModel;
using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace PrimitivesDemo;

/// <summary>
/// Draws a <see cref="DrModelInstance"/> made of <see cref="MeshPrimitives"/> parts using
/// <see cref="BasicEffect"/>. Solid parts are lit through their normals; line parts are drawn
/// unlit with <see cref="PrimitiveType.LineList"/>.
/// </summary>
internal sealed class Renderer : IDisposable
{
	private readonly GraphicsDevice _device;
	private readonly DrModelInstance _instance;
	private readonly BasicEffect _effect;

	private bool _frameOpen;

	private BlendState _savedBlendState = BlendState.Opaque;
	private DepthStencilState _savedDepthStencilState = DepthStencilState.Default;
	private RasterizerState _savedRasterizerState = RasterizerState.CullCounterClockwise;

	public Renderer(GraphicsDevice device, DrModelInstance instance)
	{
		ArgumentNullException.ThrowIfNull(device);
		ArgumentNullException.ThrowIfNull(instance);

		_device = device;
		_instance = instance;

		_effect = new BasicEffect(device)
		{
			PreferPerPixelLighting = true
		};

		_effect.AmbientLightColor = new Vector3(0.35f);
		_effect.DirectionalLight0.Enabled = true;
		_effect.DirectionalLight0.Direction =
			Vector3.Normalize(new Vector3(-0.5f, -1f, -0.4f));
		_effect.DirectionalLight0.DiffuseColor = Vector3.One;
		_effect.DirectionalLight0.SpecularColor = Vector3.Zero;
		_effect.DirectionalLight1.Enabled = false;
		_effect.DirectionalLight2.Enabled = false;
	}

	public int DrawCalls { get; private set; }

	public int Triangles { get; private set; }

	public int Lines { get; private set; }

	public BoundingSphere ComputeBounds()
	{
		return _instance.BoundingSphere;
	}

	/// <summary>
	/// Saves device state and starts a frame. Must be paired with <see cref="EndFrame"/>.
	/// </summary>
	public void BeginFrame(Matrix view, Matrix projection)
	{
		if (_frameOpen)
		{
			throw new InvalidOperationException("A renderer frame is already open.");
		}

		DrawCalls = 0;
		Triangles = 0;
		Lines = 0;
		_frameOpen = true;

		_effect.View = view;
		_effect.Projection = projection;

		_savedBlendState = _device.BlendState;
		_savedDepthStencilState = _device.DepthStencilState;
		_savedRasterizerState = _device.RasterizerState;

		_device.BlendState = BlendState.Opaque;
		_device.DepthStencilState = DepthStencilState.Default;
	}

	public void Clear(Color color)
	{
		EnsureFrameOpen();
		_device.Clear(color);
	}

	/// <summary>
	/// Draws every mesh part using the instance's current bone pose.
	/// </summary>
	public void DrawScene()
	{
		EnsureFrameOpen();

		Matrix[] absoluteBoneTransforms = _instance.AbsoluteBoneTransforms;

		foreach (DrModelMesh mesh in _instance.Model.Meshes)
		{
			foreach (DrModelMeshPart part in mesh.MeshParts)
			{
				DrawPart(part, absoluteBoneTransforms);
			}
		}
	}

	public void EndFrame()
	{
		EnsureFrameOpen();

		_frameOpen = false;

		_device.BlendState = _savedBlendState;
		_device.DepthStencilState = _savedDepthStencilState;
		_device.RasterizerState = _savedRasterizerState;
	}

	public void Dispose()
	{
		_effect.Dispose();
	}

	private void DrawPart(DrModelMeshPart part, Matrix[] absoluteBoneTransforms)
	{
		if (part.VertexBuffer is null || part.IndexBuffer is null)
		{
			return;
		}

		VertexDeclaration declaration = part.VertexDeclaration
			?? part.VertexBuffer.VertexDeclaration;

		bool isLine = part.PrimitiveType == PrimitiveType.LineList;
		bool hasNormal = HasElement(declaration, VertexElementUsage.Normal);
		Vector4 color = part.Material?.BaseColorFactor ?? Vector4.One;

		_effect.World = GetMeshWorld(part, absoluteBoneTransforms);
		_effect.DiffuseColor = new Vector3(color.X, color.Y, color.Z);
		_effect.Alpha = color.W;

		// Lines carry no normals, so lighting is disabled for them. Solid parts use the
		// per-pixel normal generated by MeshPrimitives.
		_effect.LightingEnabled = hasNormal && !isLine;
		_effect.TextureEnabled = false;

		// Primitives are built clockwise for CullCounterClockwise by default. A part built with
		// cullClockwise: true stores the rasterizer state in Tag so the draw matches its winding.
		_device.RasterizerState = part.Tag as RasterizerState
			?? (isLine ? RasterizerState.CullNone : RasterizerState.CullCounterClockwise);

		_device.SetVertexBuffer(part.VertexBuffer);
		_device.Indices = part.IndexBuffer;

		foreach (EffectPass pass in _effect.CurrentTechnique.Passes)
		{
			pass.Apply();
			_device.DrawIndexedPrimitives(
				part.PrimitiveType,
				part.VertexOffset,
				part.StartIndex,
				part.PrimitiveCount);

			++DrawCalls;

			if (isLine)
			{
				Lines += part.PrimitiveCount;
			}
			else
			{
				Triangles += part.PrimitiveCount;
			}
		}
	}

	private static Matrix GetMeshWorld(
		DrModelMeshPart part,
		Matrix[] absoluteBoneTransforms)
	{
		DrModelBone? parentBone = part.Mesh?.ParentBone;

		return parentBone is not null
			&& (uint)parentBone.Index < (uint)absoluteBoneTransforms.Length
			? absoluteBoneTransforms[parentBone.Index]
			: Matrix.Identity;
	}

	private static bool HasElement(VertexDeclaration declaration, VertexElementUsage usage)
	{
		foreach (VertexElement element in declaration.GetVertexElements())
		{
			if (element.VertexElementUsage == usage)
			{
				return true;
			}
		}

		return false;
	}

	private void EnsureFrameOpen()
	{
		if (!_frameOpen)
		{
			throw new InvalidOperationException(
				"This operation requires an open renderer frame.");
		}
	}
}
